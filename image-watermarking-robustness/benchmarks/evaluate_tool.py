"""End-to-end evaluation of the stegmark tool on real images.

Unlike src/run_experiments.py (grayscale 512x512, fixed payload), this goes
through the real tool path: colour / RGBA images at their native sizes, the
self-describing header, adaptive Reed-Solomon, PNG save + reload, then an
attack, then blind decoding (method not given, auto-detected).

Images: 8 scikit-image samples + the black-square image from the course
project. astronaut and camera are excluded because the DCT/DWT step sizes were
tuned on them in the earlier study.
Trials: 3 secret keys per image (positions keyed by the key), 27-byte message.
"""
import csv
import io
import pathlib
import sys
import time

import numpy as np
from PIL import Image
from skimage import data

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from stegmark.api import load_image, psnr, ssim                     # noqa: E402
from stegmark.attacks import ATTACKS                                # noqa: E402
from stegmark.core import embed_payload, extract_payload, capacity  # noqa: E402

OUT = ROOT / "results" / "tool"
OUT.mkdir(parents=True, exist_ok=True)
MSG = b"Karthikey Nori | owner 2026"
KEYS = ["key-A", "key-B", "key-C"]
METHODS = ["LSB", "DCT", "DWT"]


def images():
    ims = {n: getattr(data, n)() for n in
           ["coffee", "chelsea", "rocket", "immunohistochemistry", "hubble_deep_field",
            "retina", "colorwheel", "logo"]}
    ims["black_square"] = load_image(str(ROOT / "examples" / "black_square.png"))
    return ims


def png_roundtrip(a):
    buf = io.BytesIO(); Image.fromarray(a).save(buf, format="PNG")
    return np.array(Image.open(buf))


def main():
    ims = images()
    rows, quality = [], []
    for name, img in ims.items():
        for m in METHODS:
            for key in KEYS:
                t0 = time.perf_counter()
                st, info = embed_payload(img, MSG, m, password=key)
                t_emb = time.perf_counter() - t0
                st = png_roundtrip(st)
                quality.append(dict(image=name, size=f"{img.shape[1]}x{img.shape[0]}",
                                    channels=img.shape[2] if img.ndim == 3 else 1, method=m, key=key,
                                    psnr=psnr(img, st), ssim=ssim(img, st), repeats=info.body_repeats,
                                    unreliable=info.unreliable_slots, embed_s=t_emb,
                                    capacity_bytes=capacity(img.shape, m)))
                for an, atk in ATTACKS.items():
                    ex = extract_payload(atk(st), password=key)      # blind: all methods tried
                    ok = ex is not None and ex.payload == MSG and ex.method == m
                    rows.append(dict(image=name, method=m, key=key, attack=an, recovered=int(ok),
                                     detected=int(ex is not None)))
        print("done", name, flush=True)

    with open(OUT / "trials.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=rows[0].keys()); w.writeheader(); w.writerows(rows)
    with open(OUT / "quality.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=quality[0].keys()); w.writeheader()
        for q in quality:
            w.writerow({k: (round(v, 4) if isinstance(v, float) else v) for k, v in q.items()})

    n_trials = len(ims) * len(KEYS)
    rec = {(m, a): sum(r["recovered"] for r in rows if r["method"] == m and r["attack"] == a)
           for m in METHODS for a in ATTACKS}
    md = ["# stegmark end-to-end results\n",
          f"{len(ims)} images at native size ({', '.join(ims)}), {len(KEYS)} keys each = "
          f"{n_trials} trials per cell. 27-byte message, PNG save/reload, blind decoding "
          "(method auto-detected). Generated by `benchmarks/evaluate_tool.py`.\n",
          "## Exact message recovered (successes / trials)\n",
          "| Attack | " + " | ".join(METHODS) + " |", "|---|" + "---|" * len(METHODS)]
    for a in ATTACKS:
        md.append(f"| {a} | " + " | ".join(f"{rec[(m, a)]}/{n_trials}" for m in METHODS) + " |")

    md += ["\n## Imperceptibility (mean over images and keys)\n",
           "| Method | PSNR dB (mean) | PSNR dB (min) | SSIM (mean) | SSIM (min) | copies per bit (median) | embed time s (mean) |",
           "|---|---|---|---|---|---|---|"]
    for m in METHODS:
        q = [x for x in quality if x["method"] == m]
        p = [x["psnr"] for x in q]; s = [x["ssim"] for x in q]
        md.append(f"| {m} | {np.mean(p):.1f} | {np.min(p):.1f} | {np.mean(s):.4f} | {np.min(s):.4f} | "
                  f"{int(np.median([x['repeats'] for x in q]))} | {np.mean([x['embed_s'] for x in q]):.3f} |")
    md += ["\n## Per image (key-A)\n",
           "| Image | Size | LSB PSNR | DCT PSNR | DWT PSNR | DCT SSIM | DWT SSIM | DCT/DWT max message (bytes) |",
           "|---|---|---|---|---|---|---|---|"]
    for name in ims:
        g = {x["method"]: x for x in quality if x["image"] == name and x["key"] == "key-A"}
        md.append(f"| {name} | {g['LSB']['size']} | {g['LSB']['psnr']:.1f} | {g['DCT']['psnr']:.1f} | "
                  f"{g['DWT']['psnr']:.1f} | {g['DCT']['ssim']:.4f} | {g['DWT']['ssim']:.4f} | "
                  f"{g['DCT']['capacity_bytes']} / {g['DWT']['capacity_bytes']} |")
    fp = sum(1 for name, img in ims.items() if extract_payload(img, password="") is not None)
    md.append(f"\nFalse positives: {fp}/{len(ims)} clean (unmarked) images reported a watermark.")
    unrel = sum(x["unreliable"] for x in quality)
    md.append(f"Embedded slots that failed to settle after 8-bit rounding/clipping: {unrel} in total.")
    (OUT / "results.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))

    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    att = [a for a in ATTACKS if a != "none"]
    fig, ax = plt.subplots(figsize=(11, 4.6))
    x = np.arange(len(att)); wd = 0.27
    colors = {"LSB": "#9aa0a6", "DCT": "#2a6fdb", "DWT": "#e07b28"}
    for j, m in enumerate(METHODS):
        ax.bar(x + (j - 1) * wd, [rec[(m, a)] / n_trials for a in att], wd, label=m, color=colors[m])
    ax.set_xticks(x); ax.set_xticklabels(att, rotation=35, ha="right", fontsize=9)
    ax.set_ylim(0, 1.05); ax.set_ylabel("fraction of trials with exact recovery")
    ax.set_title(f"stegmark: message recovery after attack ({n_trials} trials per bar)")
    ax.legend(frameon=False); ax.spines[["top", "right"]].set_visible(False)
    plt.tight_layout(); plt.savefig(OUT / "recovery.png", dpi=150); plt.close()


if __name__ == "__main__":
    main()
